"""Шапка сетки: направление и профиль по колонкам.

Метки в источниках МПГУ пишутся десятком способов — с переносом слова внутри
ячейки («наименован ие направлени я»), одним словом («Направление»), либо
вместе со значением в одной ячейке-баннере. Всё это один и тот же смысл.
"""
from scraper.normalizer.schedule_normalizer import extract_column_headers


def test_canonical_two_row_header():
    table = [
        ["Код, наименование направления/специальности", "",
         "42.03.02 ЖУРНАЛИСТИКА", "44.03.01 ПЕДАГОГИЧЕСКОЕ ОБРАЗОВАНИЕ"],
        ["Направленность (профиль)", "", "Журналистика", "МХК"],
        ["День недели", "Группа/Время", "БОЖ09-ЖРН2101", "БОЖ09-МХК2101"],
    ]
    meta = extract_column_headers(table)
    assert meta[2] == {"direction": "42.03.02 ЖУРНАЛИСТИКА", "profile": "Журналистика"}
    assert meta[3] == {"direction": "44.03.01 ПЕДАГОГИЧЕСКОЕ ОБРАЗОВАНИЕ", "profile": "МХК"}


def test_word_wrapped_label_still_recognised():
    """journalism/philology: pdfplumber отдаёт метку с переносом ВНУТРИ слова."""
    table = [
        ["Код, наименован\nие направлени\nя", "", "42.03.02 ЖУРНАЛИСТИКА"],
        ["Направленн\nость (профиль)", "", "Телевидение"],
        ["День недели", "Группа/Время", "БОЖ09-ТВЖ2101"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["direction"] == "42.03.02 ЖУРНАЛИСТИКА"
    assert meta[2]["profile"] == "Телевидение"


def test_bare_one_word_labels():
    """math/geography подписывают колонки одним словом."""
    table = [
        ["Направление", "", "44.03.05 Педагогическое образование"],
        ["Профиль", "", "Математика и Информатика"],
        ["День", "Время", "БОМ14-МИН2101"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["direction"] == "44.03.05 Педагогическое образование"
    assert meta[2]["profile"] == "Математика и Информатика"


def test_naimenvanie_typo_survives():
    """history/xlsx: «наименвание» — опечатка в самом источнике."""
    table = [
        ["", "Код, наименвание направления:", "", "46.03.01 История"],
        ["", "Направленность (профиль)", "", "Историческая политология"],
        ["", "День недели", "Группа / Время", "ВОИ18-ИПЛ2601"],
    ]
    meta = extract_column_headers(table, data_col=3)
    assert meta[3]["direction"] == "46.03.01 История"
    assert meta[3]["profile"] == "Историческая политология"


def test_banner_cell_holds_label_and_value_together():
    """preschool: подпись и значение в ОДНОЙ ячейке, растянутой на всю сетку."""
    table = [
        ["", "", "", "Направление 44.03.02 Психолого-педагогическое образование", ""],
        ["", "", "", 'Направленность "Детская практическая психология"', ""],
        ["День недели", "Время", "БОД11-ДПП2101", "БОД11-ДПП2102", "БОД11-ДПП2103"],
    ]
    meta = extract_column_headers(table)
    for ci in (2, 3, 4):
        assert meta[ci]["direction"] == "44.03.02 Психолого-педагогическое образование"
        assert meta[ci]["profile"] == 'Детская практическая психология'


def test_profile_label_never_read_as_direction():
    """«Направленность» содержит «направлен» — но это профиль, не направление."""
    table = [
        ["Направленность (профиль)", "", "Журналистика"],
        ["День недели", "Группа/Время", "БОЖ09-ЖРН2101"],
    ]
    meta = extract_column_headers(table)
    assert meta[2].get("profile") == "Журналистика"
    assert "direction" not in meta[2]


def test_merged_direction_does_not_leak_past_the_next_one():
    table = [
        ["Направление", "", "44.03.01 Педобразование", "", "42.03.02 Журналистика", ""],
        ["День", "Время", "Г1", "Г2", "Г3", "Г4"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["direction"] == "44.03.01 Педобразование"
    assert meta[3]["direction"] == "44.03.01 Педобразование"
    assert meta[4]["direction"] == "42.03.02 Журналистика"
    assert meta[5]["direction"] == "42.03.02 Журналистика"


def test_direct_hit_beats_a_merged_carry():
    """geography: профиль расписан на ДВЕ строки — общая часть в строке с
    подписью, уточнение в безымянной строке под ней.

    Протяжка объединённой ячейки не должна затирать колонки, где под ней
    стоит собственное значение: «Общая география» принадлежит своей группе,
    а не соседнему «География и Иностранный язык».
    """
    table = [
        ["направление", "", "44.03.01 ПЕДОБРАЗОВАНИЕ", "", "05.03.02 ГЕОГРАФИЯ"],
        ["профиль", "", "", "География и Иностранный язык", ""],
        ["", "", "География", "французский", "Общая география"],
        ["группа", "", "БОГ34-ГЕО2001", "БОГ35-ГЯП2001", "БОГ03-ПГЕ2101"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["profile"] == "География"
    assert meta[3]["profile"] == "География и Иностранный язык, французский"
    assert meta[4]["profile"] == "Общая география"
    # Направление протягивается как обычно — там своя строка без уточнений.
    assert meta[2]["direction"] == "44.03.01 ПЕДОБРАЗОВАНИЕ"
    assert meta[3]["direction"] == "44.03.01 ПЕДОБРАЗОВАНИЕ"
    assert meta[4]["direction"] == "05.03.02 ГЕОГРАФИЯ"


def test_lesson_row_is_never_read_as_a_header_continuation():
    """Строка занятий под подписью — это занятия, а не продолжение шапки."""
    table = [
        ["Профиль", "", "Журналистика"],
        ["", "", "ИСТОРИЯ (ЛК)\nдоц. И.И. Иванов\nауд. 204"],
        ["День недели", "Группа/Время", "БОЖ09-ЖРН2101"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["profile"] == "Журналистика"


def test_inline_label_inside_a_group_column_cell():
    """pedagogy: направление и профиль вписаны в саму ячейку колонки.

        r: «Базовое высшее образование: 39.03.03 …» | «Направление: 37.05.01 …»
        r: «108 ГРУППА: Направленность: «Социальная психология молодежи» (код)»
    """
    table = [
        ["ДЕНЬ НЕДЕЛИ", "ВРЕМЯ",
         "Базовое высшее образование: 39.03.03 Организация работы с молодежью (01.09.2026-13.09.2026)",
         "Направление: 37.05.01 Клиническая психология (01.09.2026-13.09.2026)"],
        ["ДЕНЬ НЕДЕЛИ", "ВРЕМЯ",
         "108 ГРУППА: Направленность: «Социальная психология молодежи» (ВОП30-СПМ2608)",
         "107 ГРУППА: Направленность: «Психодиагностика» (СОП13-ПКП2607)"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["direction"] == "39.03.03 Организация работы с молодежью"
    assert meta[3]["direction"] == "37.05.01 Клиническая психология"
    assert meta[2]["profile"] == "Социальная психология молодежи"
    assert meta[3]["profile"] == "Психодиагностика"


def test_quoted_specialnost_is_a_profile_not_a_direction():
    """«Специальность: «…»» в кавычках — это профиль. Направление узнаётся
    по коду ОКСО в начале значения, а не по слову подписи."""
    table = [
        ["ДЕНЬ НЕДЕЛИ", "ВРЕМЯ",
         "101 ГРУППА Специальность: «Психология и педагогика. Профессиональное консультирование» (ВОП40-ПФК2601)"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["profile"] == "Психология и педагогика. Профессиональное консультирование"
    assert "direction" not in meta[2]


def test_inline_banner_does_not_leak_into_a_column_with_its_own_text():
    """Соседняя колонка со СВОИМ текстом обрывает протяжку баннера."""
    table = [
        ["ДЕНЬ", "ВРЕМЯ",
         "Направление: 37.05.01 Клиническая психология",
         "",
         "Базовое высшее образование: 39.03.03 Организация работы с молодежью"],
        ["ДЕНЬ", "ВРЕМЯ", "ВОП30-КЛП2601", "ВОП30-КЛП2602", "ВОП31-ОРМ2601"],
    ]
    meta = extract_column_headers(table)
    assert meta[2]["direction"] == "37.05.01 Клиническая психология"
    assert meta[3]["direction"] == "37.05.01 Клиническая психология"
    assert meta[4]["direction"] == "39.03.03 Организация работы с молодежью"


def test_prose_mentioning_a_label_is_not_a_header():
    """Слово «направление» в тексте занятия — не подпись шапки."""
    table = [
        ["ПОНЕДЕЛЬНИК", "09:00-10:30",
         "Профориентация: выбираем направление будущей работы (ЛК) доц. И.И. Иванов"],
    ]
    assert extract_column_headers(table) == {}
